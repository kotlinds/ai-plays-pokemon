internal object HgssItemPrices {

    /** Price of [itemId] in Poké Dollars, null when the item has no price. */
    fun price(itemId: Int): Int? {
        val data = HgssData.gameData ?: return PRICES[itemId]
        return data.item(ItemId(itemId))?.price?.takeIf { it != 0 }
    }

    /** Price of [itemId] in the bundled table (ignores the ROM), null when the item has no price. */
    fun bundledPrice(itemId: Int): Int? = PRICES[itemId]

