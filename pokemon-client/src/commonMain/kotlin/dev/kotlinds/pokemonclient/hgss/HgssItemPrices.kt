/**
 * Buying price of every item (`ItemData.price`, the `price` column of files/itemtool/itemdata/item_data.csv in
 * pret/pokeheartgold, mapped from item id to data index through `sItemNarcIds` in src/item.c).
 *
 * Why a static table: a normal Poké Mart computes the price with `GetItemAttr(item, ITEMATTR_PRICE)` only for the
 * item being bought (src/overlay_03/shop_menu.c, MartData.cost), so the prices of the listed items are never in RAM.
 * The table is the same for every HG/SS release. Items absent from the table cost 0 (not sellable / key items).
